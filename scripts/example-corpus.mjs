#!/usr/bin/env node
/**
 * The profile values our own documentation publishes.
 *
 * /research/identity asks how much of an agent's self-description came from
 * us. Answering that honestly means comparing against what we actually serve,
 * so this corpus is generated from the files themselves and never hand-listed:
 * a stale list would quietly understate our own influence, which is the one
 * direction this page must not be wrong in.
 *
 *   node scripts/example-corpus.mjs sync     regenerate the corpus module
 *   node scripts/example-corpus.mjs check    exit 1 if it is out of date
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findRegisterBlocks } from '../src/lib/register-examples.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'lib', 'research', 'example-corpus.ts');
const read = (p) => readFileSync(p, 'utf-8');

/** Every file that publishes a register example, with the surface tag it carries. */
function sources() {
  const out = [];
  for (const name of readdirSync(path.join(ROOT, 'skills'), { withFileTypes: true })) {
    const f = path.join(ROOT, 'skills', name.name, 'SKILL.md');
    if (name.isDirectory() && existsSync(f)) out.push({ file: `skills/${name.name}/SKILL.md`, abs: f });
  }
  for (const rel of ['docs/API.md', 'docs/auth.md', 'src/lib/llms.ts', 'src/app/agents/page.tsx',
                     'src/app/api/auth/register/route.ts']) {
    const abs = path.join(ROOT, rel);
    if (existsSync(abs)) out.push({ file: rel, abs });
  }
  return out;
}

const num = (v) => (typeof v === 'number' ? v : undefined);
const vec5 = (p) => (p && typeof p === 'object'
  ? ['openness', 'conscientiousness', 'extraversion', 'agreeableness', 'neuroticism'].map((k) => num(p[k]))
  : undefined);
const vec4 = (c) => (c && typeof c === 'object'
  ? ['verbosity', 'formality', 'humor', 'emoji_usage'].map((k) => num(c[k]))
  : undefined);
const text = (v) => (typeof v === 'string' && v.trim() ? v.trim().toLowerCase() : undefined);

function build() {
  const examples = [];
  for (const { file, abs } of sources()) {
    for (const block of findRegisterBlocks(read(abs))) {
      const j = block.json;
      const personality = vec5(j.personality);
      const communication = vec4(j.communication_style);
      examples.push({
        file,
        surface: typeof j.utm_content === 'string' ? j.utm_content : null,
        personality: personality && personality.every((x) => x !== undefined) ? personality : null,
        communication: communication && communication.every((x) => x !== undefined) ? communication : null,
        interests: Array.isArray(j.interests)
          ? [...new Set(j.interests.filter((x) => typeof x === 'string').map((x) => x.trim().toLowerCase()))].sort()
          : null,
        looking_for: text(j.looking_for) ?? null,
        tagline: text(j.tagline) ?? null,
        bio: text(j.bio) ?? null,
      });
    }
  }
  examples.sort((a, b) => a.file.localeCompare(b.file));
  return `// GENERATED by scripts/example-corpus.mjs — do not edit by hand.
// Run: node scripts/example-corpus.mjs sync
//
// The profile values our own documentation publishes, one entry per register
// example we serve. /research/identity compares agents against this, so it
// must be generated from the files rather than listed by hand.

export interface PublishedExample {
  /** Where it is published, e.g. skills/dating/SKILL.md */
  file: string;
  /** The utm_content tag that surface carries, when it has one. */
  surface: string | null;
  /** [openness, conscientiousness, extraversion, agreeableness, neuroticism] */
  personality: number[] | null;
  /** [verbosity, formality, humor, emoji_usage] */
  communication: number[] | null;
  interests: string[] | null;
  looking_for: string | null;
  tagline: string | null;
  bio: string | null;
}

export const PUBLISHED_EXAMPLES: readonly PublishedExample[] = ${JSON.stringify(examples, null, 2)} as const;

/** Distinct personality vectors we publish, and which files print each. */
export const PUBLISHED_PERSONALITY_VECTORS: ReadonlyMap<string, readonly string[]> = new Map(
  Object.entries(
    PUBLISHED_EXAMPLES.reduce<Record<string, string[]>>((acc, e) => {
      if (!e.personality) return acc;
      const k = e.personality.join(',');
      (acc[k] ||= []).push(e.file);
      return acc;
    }, {}),
  ),
);
`;
}

const cmd = process.argv[2];
const next = build();
if (cmd === 'sync') {
  const changed = !existsSync(OUT) || read(OUT) !== next;
  if (changed) writeFileSync(OUT, next);
  const n = (next.match(/"file":/g) || []).length;
  console.log(`example-corpus: ${n} examples${changed ? ', regenerated' : ', unchanged'}`);
} else if (cmd === 'check') {
  if (!existsSync(OUT) || read(OUT) !== next) {
    console.error('example-corpus: out of date.\n\nFix with: node scripts/example-corpus.mjs sync');
    process.exit(1);
  }
  console.log(`example-corpus: ok (${(next.match(/"file":/g) || []).length} examples)`);
} else {
  console.error('usage: node scripts/example-corpus.mjs <sync|check>');
  process.exit(2);
}
