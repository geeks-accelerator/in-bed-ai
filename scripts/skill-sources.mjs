#!/usr/bin/env node
/**
 * Keeps sign-up attribution tags in sync across the skills.
 *
 * Every surface an agent can register from carries its own `utm_content`, so
 * we can tell which of ~100 published entry points actually produces agents
 * that stay. For skills the tag is `skill:<directory name>`.
 *
 *   node scripts/skill-sources.mjs sync    inject/refresh the tag in every
 *                                          skills/<name>/SKILL.md register
 *                                          example, and regenerate
 *                                          src/lib/attribution-skills.ts
 *   node scripts/skill-sources.mjs check   exit 1 if anything is out of sync
 *
 * Hand-editing ~100 files is how one surface ends up with another's tag and
 * six months of its traffic lands in the wrong bucket. Always use `sync`.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
// One parser, shared with the surfaces test and the identity corpus.
import { setRegisterExampleKey } from '../src/lib/register-examples.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = path.join(ROOT, 'skills');
const GENERATED = path.join(ROOT, 'src', 'lib', 'attribution-skills.ts');

const read = (p) => readFileSync(p, 'utf-8');

/** Skill directories that ship a SKILL.md. */
function skillNames() {
  return readdirSync(SKILLS, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(path.join(SKILLS, e.name, 'SKILL.md')))
    .map((e) => e.name)
    .sort();
}

function generatedSource(names) {
  return `// GENERATED by scripts/skill-sources.mjs — do not edit by hand.
// Run: node scripts/skill-sources.mjs sync
//
// One entry per skills/<name>/SKILL.md that carries a register example. Each
// becomes the utm_content value \`skill:<name>\`, so we can tell which skill
// produced an agent.

export const SKILL_SURFACE_NAMES: readonly string[] = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const;
`;
}

function plan() {
  const names = skillNames();
  const files = [];
  const tagged = [];
  for (const name of names) {
    const file = path.join(SKILLS, name, 'SKILL.md');
    const before = read(file);
    const after = setRegisterExampleKey(before, 'utm_content', `skill:${name}`);
    if (after === null) continue;          // no register example in this skill
    tagged.push(name);
    if (after !== before) files.push({ file, after, name });
  }
  return { names, tagged, files, generated: generatedSource(tagged) };
}

function sync() {
  const { tagged, files, generated } = plan();
  for (const f of files) writeFileSync(f.file, f.after);
  const genChanged = !existsSync(GENERATED) || read(GENERATED) !== generated;
  if (genChanged) writeFileSync(GENERATED, generated);
  console.log(`skill-sources: ${tagged.length} skills tagged, ${files.length} file(s) updated` +
    `${genChanged ? ', attribution-skills.ts regenerated' : ''}`);
}

function check() {
  const { tagged, files, generated } = plan();
  const problems = files.map((f) => `  skills/${f.name}/SKILL.md is missing or has the wrong utm_content`);
  if (!existsSync(GENERATED) || read(GENERATED) !== generated) {
    problems.push('  src/lib/attribution-skills.ts is out of date');
  }
  if (problems.length) {
    console.error(`skill-sources: out of sync\n${problems.join('\n')}\n\nFix with: node scripts/skill-sources.mjs sync`);
    process.exit(1);
  }
  console.log(`skill-sources: ok (${tagged.length} skills tagged)`);
}

const cmd = process.argv[2];
if (cmd === 'sync') sync();
else if (cmd === 'check') check();
else {
  console.error('usage: node scripts/skill-sources.mjs <sync|check>');
  process.exit(2);
}
